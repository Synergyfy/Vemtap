import { Controller, Get, Query, Req, UseGuards } from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { RolesGuard } from '../../common/guards/roles.guard';
import { PermissionsGuard } from '../../common/guards/permissions.guard';
import { Roles } from '../../common/decorators/roles.decorator';
import { Permissions } from '../../common/decorators/permissions.decorator';
import { UserRole } from '../users/entities/user.entity';
import { BusinessQrService } from './business-qr.service';
import { AnalyticsRangeQueryDto } from './dto/analytics-range.dto';

interface BusinessRequest {
  user: { businessId: string };
}

@ApiTags('Business QR')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard, RolesGuard, PermissionsGuard)
@Roles(UserRole.OWNER, UserRole.MANAGER)
@Permissions('qrthrive', 'marketing')
@Controller('business-qr')
export class BusinessQrController {
  constructor(private readonly qr: BusinessQrService) {}

  @Get('summary')
  @ApiOperation({
    summary: 'Business, branch and tap-point QR codes with scan counts',
    description:
      'QR codes are generated by VemTap (no external service): the business link ' +
      '`/b/{businessCode}`, one per branch `/b/{branchCode}` and one per tap device ' +
      '`/{branchUsername}/{deviceCode}`, each as `{ url, svg }`. Scans are the visits ' +
      'those taps recorded in the period, compared with the previous period. Same ' +
      '`from`/`to`/`branchId` range as `/business-analytics`.',
  })
  @ApiResponse({ status: 200, description: 'QR summary for the period' })
  summary(@Req() req: BusinessRequest, @Query() query: AnalyticsRangeQueryDto) {
    return this.qr.getSummary(req.user.businessId, query);
  }

  @Get('kit')
  @ApiOperation({
    summary: 'Printable PDF of every QR code (business, branches, tap points)',
    description:
      'Returns `{ filename, mimeType, contentBase64, sizeBytes, codes }`.',
  })
  @ApiResponse({ status: 200, description: 'PDF kit, base64-encoded' })
  kit(@Req() req: BusinessRequest, @Query() query: AnalyticsRangeQueryDto) {
    return this.qr.getKit(req.user.businessId, query);
  }
}
